#!/usr/bin/env bash
# PreToolUse (Edit|Write): block edits to files that define "correct" or hold secrets/raw data.
# To allow an edit for one session, the OWNER runs: touch .claude/.unlock-protected
# (and deletes it afterwards). Claude is blocked from creating that file.
set -uo pipefail
INPUT=$(cat)
FILE_PATH=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // empty')
[ -z "$FILE_PATH" ] && exit 0
FILE_PATH="${FILE_PATH//\\//}"
ROOT="${CLAUDE_PROJECT_DIR:-$(pwd)}"
REL="${FILE_PATH#"$ROOT"/}"

# Never unlockable
case "$REL" in
  .env|.env.*|*/.env) [ "$REL" = ".env.example" ] && exit 0
    echo "Blocked: $REL holds secrets. Ask the owner to edit it." >&2; exit 2 ;;
  .claude/.unlock-protected)
    echo "Blocked: only the owner may create the unlock file." >&2; exit 2 ;;
esac

# Unlockable by the owner
PROTECTED=("uv.lock" "data/raw/" "evals/golden.yaml" "evals/retrieval_labels.yaml" "evals/crosscheck_vehicles.yaml" "tests/fixtures/")
for p in "${PROTECTED[@]}"; do
  if [[ "$REL" == "$p" || "$REL" == "$p"* ]]; then
    if [ -f "$ROOT/.claude/.unlock-protected" ]; then exit 0; fi
    {
      echo "Blocked: $REL is protected (pattern '$p')."
      echo "These files define what 'correct' means or are generated by tools."
      echo "Explain to the owner why the change is needed and ask them to approve it"
      echo "(they unlock with: touch .claude/.unlock-protected). For uv.lock use 'uv add'."
    } >&2
    exit 2
  fi
done
exit 0
